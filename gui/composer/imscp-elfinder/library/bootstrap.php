declare(strict_types=1);

// Never display errors to the client (the panel PHP-FPM pool enables
// display_errors).
ini_set('display_errors', '0');
ini_set('log_errors', '1');

require_once __DIR__ . '/App.php';

/**
 * Get the front-end application instance
 *
 * The configuration file is generated by the i-MSCP package handler.
 *
 * @return \iMSCP\ElFinder\App
 */
function imscp_elfinder_app()
{
    static $app;

    if (NULL === $app) {
        $configFile = __DIR__ . '/../config.php';

        $config = is_file($configFile) ? include $configFile : NULL;
        if (!is_array($config)) {
            http_response_code(503);
            header('Content-Type: text/plain; charset=utf-8');
            echo "The file manager is not configured.\n";
            exit;
        }

        try {
            $app = new \iMSCP\ElFinder\App($config);
        } catch (\Throwable $e) {
            error_log('i-MSCP elFinder: ' . $e->getMessage());
            http_response_code(503);
            header('Content-Type: text/plain; charset=utf-8');
            echo "The file manager is not available.\n";
            exit;
        }
    }

    return $app;
}

/**
 * Get path to the upstream elFinder installation directory
 *
 * @return string
 */
function imscp_elfinder_upstream_dir()
{
    return dirname(__DIR__) . '/elfinder';
}
