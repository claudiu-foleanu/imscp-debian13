=head1 DESCRIPTION

 i-MSCP PhpMyAdmin package handler.

 The phpMyAdmin application is not shipped with this package. The pinned
 upstream release (see %UPSTREAM below) is downloaded from
 https://files.phpmyadmin.net/ at setup time, verified against the pinned
 SHA-256 checksum and extracted into the
 <GUI_ROOT_DIR>/vendor/imscp/phpmyadmin/phpmyadmin directory.

 The release tarball ships with all PHP dependencies and compiled assets.

 The control panel directory tree is owned by the control panel user. Any
 operation made in that tree is made with the privileges of that user (see
 _runAsPanelUser()). The phpMyAdmin configuration storage schema is taken from
 the verified release archive, not from the installed tree, and is executed
 through DBI (statement by statement, only expected statements).

=cut

# Pinned upstream release. phpMyAdmin 5.2.x requires PHP >= 7.2.5.
# Checksum is the one published at <url>.sha256; release tarball signature
# verified with the phpMyAdmin release key
# (3D06A59ECE730EB71B511C17CE752F178259BD92).
my %UPSTREAM = (
    version => '5.2.3',
    url     => 'https://files.phpmyadmin.net/phpMyAdmin/5.2.3/phpMyAdmin-5.2.3-all-languages.tar.gz',
    sha256  => '12ba1c425fa4071abbd4e7668c9ebdeac0b0755a467a6d6d5026122bb47c102b'
);

# Nginx configuration snippet (included in the control panel vhost files).
# Embedded on purpose: the package directory is writable by the control panel
# user and this file is installed as root in the Nginx configuration
# directory.
my $NGINX_CONF = <<'EOF';
# phpMyAdmin - auto-generated by i-MSCP
#     DO NOT EDIT THIS FILE BY HAND -- YOUR CHANGES WILL BE OVERWRITTEN

location = /phpmyadmin {
    return 301 /phpmyadmin/;
}

location ^~ /phpmyadmin/ {
    # {GUI_ROOT_DIR}/public/tools/phpmyadmin is a symlink to the phpMyAdmin
    # installation directory
    root {GUI_ROOT_DIR}/public/tools;

    # Deny access to hidden files and to non-public directories/files
    location ~ /\. {
        deny all;
    }

    location ~ ^/phpmyadmin/(?:setup|sql|libraries|templates|vendor|locale|examples|test|doc)/ {
        deny all;
    }

    location ~ ^/phpmyadmin/(?:config\.inc\.php|config\.sample\.inc\.php|composer\.(?:json|lock)|package\.json|yarn\.lock|babel\.config\.json|ChangeLog|README|LICENSE|CONTRIBUTING\.md|RELEASE-DATE-.*)$ {
        deny all;
    }

    location ~ \.php$ {
        include imscp_fastcgi.conf;
    }
}
EOF

=head1 PUBLIC METHODS

=over 4

=item preinstall( )

 Pre-installation tasks

 Return int 0 on success, other on failure

=cut

sub preinstall
{
    my ( $self ) = @_;

    my $rs = $self->_installUpstream();
    return $rs if $rs;

    $self->{'events'}->register(
        'afterFrontEndBuildConfFile', \&afterFrontEndBuildConfFile
    );
}

=item install( )

 Installation tasks

 Return int 0 on success, other on failure

=cut

sub install
{
    my ( $self ) = @_;

    local $CWD = $::imscpConfig{'GUI_ROOT_DIR'};

    local $@;
    eval {
        my $guiDir = $::imscpConfig{'GUI_ROOT_DIR'};
        _runAsPanelUser( sub {
            iMSCP::Dir->new( dirname => "$guiDir/data/tmp/phpmyadmin" )->make( {
                mode => 0750
            } );
            # Dedicated session directory (not shared with the control panel)
            iMSCP::Dir->new( dirname => "$guiDir/data/sessions/phpmyadmin" )->make( {
                mode => 0700
            } );
        } );
    };
    if ( $@ ) {
        error( $@ );
        return 1;
    }

    my $rs = $self->_buildConfigFiles();
    $rs ||= $self->_buildHttpdConfigFile();
    $rs ||= $self->_setupDatabase();
    $rs ||= $self->_setupSqlUser();
}

=item postinstall( )

 Post-installation tasks

 Return int 0 on success, other on failure

=cut

sub postinstall
{
    my $guiDir = $::imscpConfig{'GUI_ROOT_DIR'};

    local $@;
    eval {
        _runAsPanelUser( sub {
            if ( -l "$guiDir/public/tools/phpmyadmin" ) {
                unlink( "$guiDir/public/tools/phpmyadmin" ) or die( sprintf(
                    "Couldn't remove the %s symlink: %s",
                    "$guiDir/public/tools/phpmyadmin", $!
                ));
            }

            symlink(
                File::Spec->abs2rel(
                    "$guiDir/vendor/imscp/phpmyadmin/phpmyadmin",
                    "$guiDir/public/tools"
                ),
                "$guiDir/public/tools/phpmyadmin"
            ) or die( sprintf(
                "Couldn't create symlink for the PhpMyAdmin SQL administration tool: %s",
                $!
            ));
        } );
    };
    if ( $@ ) {
        error( $@ );
        return 1;
    }

    0;
}

=item uninstall( )

 Uninstallation tasks

 Return int 0 on success, other on failure

=cut

sub uninstall
{
    my ( $self ) = @_;

    local $CWD = $::imscpConfig{'GUI_ROOT_DIR'};

    if ( -l "$CWD/public/tools/phpmyadmin" ) {
        my $rs = iMSCP::File->new(
            filename => "$CWD/public/tools/phpmyadmin"
        )->delFile();
        return $rs if $rs;
    }

    if ( -f '/etc/nginx/imscp_pma.conf' ) {
        my $rs = iMSCP::File->new(
            filename => '/etc/nginx/imscp_pma.conf'
        )->delFile();
        return $rs if $rs;
    }

    local $@;
    eval {
        _removeDirAsPanelUser(
            "$CWD/vendor/imscp/phpmyadmin/phpmyadmin",
            "$CWD/data/tmp/phpmyadmin",
            "$CWD/data/sessions/phpmyadmin",
            $self->_getCacheDir()
        );

        $self->{'dbh'}->do(
            "DROP DATABASE IF EXISTS `@{ [ $::imscpConfig{'DATABASE_NAME'} . '_pma' ] }`"
        );

        my ( $controlUser ) = @{ $self->{'dbh'}->selectcol_arrayref(
            "SELECT `value` FROM `config` WHERE `name` = 'PMA_CONTROL_USER'"
        ) };

        if ( defined $controlUser ) {
            $controlUser = decryptRijndaelCBC(
                $::imscpDBKey, $::imscpDBiv, $controlUser
            );

            for my $host (
                $::imscpOldConfig{'DATABASE_USER_HOST'},
                $::imscpConfig{'DATABASE_USER_HOST'}
            ) {
                next unless length $host;
                Servers::sqld->factory()->dropUser( $controlUser, $host );
            }
        }

        $self->{'dbh'}->do( "DELETE FROM `config` WHERE `name` LIKE 'PMA_%'" );
    };
    if ( $@ ) {
        error( $@ );
        return 1;
    }

    0;
}

=back

=head1 EVENT LISTENERS

=over 4

=item afterFrontEndBuildConfFile( )

 Event listener that injects Httpd configuration for PhpMyAdmin into the i-MSCP
 control panel Nginx vhost files

 Return int 0 on success, other on failure

=cut

sub afterFrontEndBuildConfFile
{
    my ( $tplContent, $tplName ) = @_;

    return 0 unless grep ( $_ eq $tplName, qw/
        00_master.nginx 00_master_ssl.nginx
    / );

    ${ $tplContent } = replaceBloc(
        "# SECTION custom BEGIN.\n",
        "# SECTION custom END.\n",
        "    # SECTION custom BEGIN.\n"
            . getBloc(
                "# SECTION custom BEGIN.\n",
                "# SECTION custom END.\n",
                ${ $tplContent }
            )
            . "    include imscp_pma.conf;\n"
            . "    # SECTION custom END.\n",
        ${ $tplContent }
    );

    0;
}

=back

