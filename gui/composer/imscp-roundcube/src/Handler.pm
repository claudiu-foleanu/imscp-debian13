    version => '1.6.20',
    url     => 'https://github.com/roundcube/roundcubemail/releases/download/1.6.20/roundcubemail-1.6.20-complete.tar.gz',
    sha256  => '46919c70c85609b57038903c4ecc4e1d7fa4e14c535fe5b14192d778dcd4a1ee'
);

